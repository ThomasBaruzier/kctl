def add_course(archive, key, folder):
  archive.item(key, {
    "title": Path(folder).name,
    "path": folder + "/index.md",
    "folder": folder,
    "status": "archived",
    "parent": "index",
    "course_id": key.removeprefix("course/"),
    "include_submissions": True,
    "children": [],
  }, None)
  children = archive.data["items"]["index"]["children"]
  archive.item("index", {
    "children": list(dict.fromkeys([*children, key])),
  }, None)


def add_page(
  archive,
  key=OWNER,
  body="Course instructions\n",
  *,
  course=COURSE,
  filename="page.md",
):
  folder = archive.data["items"][course]["folder"]
  path = folder + "/" + filename
  archive.item(key, {
    "title": filename,
    "path": path,
    "folder": folder,
    "status": "archived",
    "parent": course,
    "source": "https://ctl.kmu.ac.kr/Course.do?cmd=viewStudyHome",
    "documents": [],
    "related": [],
    "problems": [],
    "empty_listing": False,
  }, body)
  children = archive.data["items"][course]["children"]
  archive.item(course, {
    "children": list(dict.fromkeys([*children, key])),
  }, None)
  return path


def add_document(
  archive,
  name="source.txt",
  raw=b"Attachment source\n",
  *,
  owner=OWNER,
  role="attachment",
  attach=True,
):
  if owner not in archive.data["items"]:
    add_page(archive, owner)

  number = len(archive.data["documents"]) + 1
  url = f"https://ctl.kmu.ac.kr/fileDownServlet?id={number}"
  key = identity(owner, url)
  folder = archive.data["items"][owner]["folder"] + f"/Document-{number}"
  work = archive.new_work()
  archive.mkdir(work + "/new")
  archive.write(work + "/new/" + name, raw)
  record = {
    "owner": owner,
    "url": url,
    "name": name,
    "folder": folder,
    "original": name,
    "role": role,
    "bytes": len(raw),
    "sha256": digest(raw),
    "signature": signature(archive.path(work + "/new/" + name)),
    "cache": "downloaded",
    "result": None,
    "attempts": {},
  }
  archive.document(key, record, work)

  if attach:
    references = archive.data["items"][owner]["documents"]
    archive.item(owner, {"documents": [*references, key]}, None)

  return key


def install_products(
  archive,
  key,
  *,
  converted=b"Converted source\n",
  recognized=None,
  convert_problems=(),
  convert_summary=None,
  ocr_summary=None,
  old_settings=False,
  children=(),
  child_results=None,
  coverage=(),
  retained_problems=(),
  retained_coverage=(),
):
  doc = copy.deepcopy(archive.data["documents"][key])
  root = {
    "name": doc["name"],
    "original": doc["original"],
    "kind": named_kind(doc["original"]),
    "sha256": doc["sha256"],
    "bytes": doc["bytes"],
    "children": [],
    "problems": [],
    "retry": False,
    "visuals": None,
    "products": {},
    "attempts": {},
  }
  nodes = {"": root}
  contents = {}
  work = archive.new_work()
  archive.mkdir(work + "/new")
  original = archive.read(
    doc["folder"] + "/" + doc["original"], 1024 * 1024
  )
  archive.write(work + "/new/" + doc["original"], original)

  for step, body in (("convert", converted), ("ocr", recognized)):
    if body is None:
      continue

    settings = copy.deepcopy(archive.settings[step])
    if old_settings:
      settings["version"] = -1

    summary = copy.deepcopy(
      (convert_summary if step == "convert" else ocr_summary) or {}
    )
    problems = []
    if step == "convert":
      problems = list(convert_problems) + list(coverage)
      if coverage:
        summary["coverage"] = list(coverage)

    markdown = "text.md" if step == "convert" else "ocr.md"
    prefix = b"# Generated header\n\n"
    appendix = b"\n## Extracted images\nGenerated asset menu\n"
    product = outcome(
      settings,
      outputs={markdown} if body else set(),
      markdown=markdown if body else None,
      content_bytes=len(body),
      content_sha256=digest(body),
      problems=problems,
      summary=summary,
    )
    if body:
      product["header_bytes"] = len(prefix)
      contents[markdown] = prefix + body + appendix

    root["products"][step] = product
    root["attempts"][step] = attempt_record(product, retained=False)

    if step == "convert" and (retained_problems or retained_coverage):
      attempt = outcome(
        archive.settings[step],
        problems=list(retained_problems) + list(retained_coverage),
        summary={"coverage": list(retained_coverage)},
      )
      root["attempts"][step] = attempt_record(attempt, retained=True)

  for index, (name, raw) in enumerate(children, 1):
    folder = f"contents/member-{index}"
    original_name = Path(name).name
    root["children"].append(folder)
    nodes[folder] = {
      "name": name,
      "original": original_name,
      "kind": named_kind(name),
      "sha256": digest(raw),
      "bytes": len(raw),
      "children": [],
      "problems": [],
      "retry": False,
      "visuals": None,
      "products": {},
      "attempts": {},
    }
    contents[folder + "/" + original_name] = raw

    if index in (child_results or {}):
      text, problems = child_results[index]
      markdown = folder + "/text.md" if text else None
      product = outcome(
        archive.settings["convert"],
        outputs={markdown} if markdown else set(),
        markdown=markdown,
        problems=list(problems),
        content_bytes=len(text),
        content_sha256=digest(text),
      )
      nodes[folder]["products"]["convert"] = product
      nodes[folder]["attempts"]["convert"] = attempt_record(product, False)

      if markdown:
        contents[markdown] = text

  for folder, node in nodes.items():
    if node_index(node):
      contents[join_path(folder, "index.md")] = b"# Generated container index\n"

  for relative, raw in contents.items():
    archive.write(work + "/new/" + relative, raw)

  doc["result"] = {
    "source": doc["sha256"],
    "settings": copy.deepcopy(archive.settings["walk"]),
    "nodes": nodes,
    "files": {relative: len(raw) for relative, raw in contents.items()},
    "finished": "2026-11-04T00:00:00+00:00",
  }
  archive.install("documents", key, doc, work)
  return archive.data["documents"][key]


def exported(archive, name="Course"):
  return archive.read(f"extracted/{name}.txt", 1024 * 1024).decode()


def notes(archive, name="Course"):
  return exported(archive, name).rsplit("## Extraction notes\n", 1)[1]


def previous_export(archive, name="Course", raw=b"Previous valid export\n"):
  archive.mkdir("extracted")
  archive.write(f"extracted/{name}.txt", raw)
  return raw


def test_export_uses_only_source_content_not_generated_views(archive):
  add_page(
    archive,
    body=(
      "## Documents\nFetched: actual source text.\n"
      "[Original source link](https://example.com)\n"
    ),
  )
  key = add_document(archive, "lesson.pdf", b"%PDF-original")
  install_products(
    archive,
    key,
    converted=b"Document source\n",
    recognized=b"OCR supplement\n",
  )
  archive.flush_views()

  assert export_courses(archive, [COURSE]) == 0
  text = exported(archive)

  assert "## Documents" in text
  assert "Fetched: actual source text." in text
  assert "https://example.com" in text
  assert "Document source" in text
  assert "OCR supplement" in text
  assert "Generated header" not in text
  assert "Generated asset menu" not in text
  assert "## Extracted images" not in text
  assert "[Back]" not in text
  assert "Source: <https://ctl.kmu.ac.kr" not in text
  assert text.endswith(EMPTY_NOTES + "\n" + OCR_NOTE + "\n")


