def test_repeated_container_labels_are_inherited_by_their_descendants(archive):
  key = add_document(archive, "project.zip", b"container")
  doc = copy.deepcopy(install_products(
    archive,
    key,
    converted=None,
    children=[
      ("same.zip", b"nested first"),
      ("same.zip", b"nested second"),
    ],
  ))
  nodes = doc["result"]["nodes"]
  work = archive.new_work()
  archive.mkdir(work + "/new")

  for relative in [doc["original"], *doc["result"]["files"]]:
    archive.write(
      work + "/new/" + relative,
      archive.read(doc["folder"] + "/" + relative, 1024 * 1024),
    )

  for index in (1, 2):
    parent = f"contents/member-{index}"
    assert parent + "/index.md" in doc["result"]["files"]
    child = parent + "/contents/source"
    raw = f"Source {index}\n".encode()
    nodes[parent]["children"] = [child]
    nodes[child] = {
      "name": "source.txt",
      "original": "source.txt",
      "kind": ".txt",
      "sha256": digest(raw),
      "bytes": len(raw),
      "children": [],
      "problems": [],
      "retry": False,
      "visuals": None,
      "products": {},
      "attempts": {},
    }
    relative = child + "/source.txt"
    archive.write(work + "/new/" + relative, raw)
    doc["result"]["files"][relative] = len(raw)

  archive.install("documents", key, doc, work)
  archive.validate()
  exporter = CourseExporter(archive, COURSE)
  exporter.gather()
  origins = {
    candidate.origin
    for candidates in exporter.groups.values()
    for candidate in candidates
    if candidate.node["name"] == "source.txt"
  }

  assert origins == {
    "Course/page.md / project.zip / same.zip (member-1) / source.txt",
    "Course/page.md / project.zip / same.zip (member-2) / source.txt",
  }
  assert export_courses(archive, [COURSE]) == 0
  text = exported(archive)
  assert all(origin in text for origin in origins)
  assert text.count("Source 1") == 1
  assert text.count("Source 2") == 1
  assert text.endswith(EMPTY_NOTES)


@pytest.mark.parametrize("step", ["convert", "ocr"])
@pytest.mark.parametrize(
  ("state", "should_process"),
  [
    ("fixed", False),
    ("retryable", True),
    ("outdated", True),
    ("retained-fixed", False),
    ("retained-retryable", True),
    ("root-failure", True),
  ],
)
def test_unavailable_product_advice_matches_processing_eligibility(
  archive, step, state, should_process
):
  key = add_document(archive, "reading.pdf", b"%PDF-original")
  doc = install_products(
    archive,
    key,
    converted=b"\n",
    recognized=b"\n",
    convert_problems=["Known extraction limitation"],
  )
  node = doc["result"]["nodes"][""]
  product = node["products"][step]
  product.update({
    "status": "partial",
    "problems": ["Known extraction limitation"],
    "retry": state in {"retryable", "retained-fixed"},
  })
  if state in {"outdated", "retained-fixed"}:
    product["settings"]["version"] = -1
  node["attempts"][step] = attempt_record(product, retained=False)

  if state.startswith("retained-"):
    latest = outcome(
      archive.settings[step],
      problems=["Latest extraction limitation"],
      retry=state == "retained-retryable",
    )
    node["attempts"][step] = attempt_record(latest, retained=True)

  if state == "root-failure":
    archive.processing_failure(key, [step], "Latest root attempt failed")

  archive.validate()
  assert archive.reusable(doc, [step]) is (not should_process)
  assert export_courses(archive, [COURSE]) == 3
  footer = notes(archive)
  advice = "run kctl process" if should_process else "original retained"
  opposite = "original retained" if should_process else "run kctl process"

  assert f"no usable {step} result; {advice}" in footer
  assert f"no usable {step} result; {opposite}" not in footer
  assert "Known extraction limitation" in footer
  assert "--force" not in footer
  assert "Sources with notes: 1" in footer
  assert archive.read(doc["folder"] + "/reading.pdf", 4096) == b"%PDF-original"


